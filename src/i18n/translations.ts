export type TranslationKey = keyof (typeof dict)['en'];

export const LanguageContext = createContext<Language>('en');

export const LanguageProvider: React.FC<{
  language?: Language;
  children: React.ReactNode;
}> = ({ language = 'en', children }) => {
  return React.createElement(LanguageContext.Provider, { value: language }, children);
};

/**
 * Universal useTranslation hook.
 * Reads language from LanguageContext by default, or accepts an explicit language override.
 * Returns `t(key)` function to retrieve translated strings.
 */
export function useTranslation(overrideLang?: Language) {
  const contextLang = useContext(LanguageContext);
  const effectiveLang: Language = overrideLang || contextLang || 'en';
  const currentLang: Language = dict[effectiveLang] ? effectiveLang : 'en';

  const t = useCallback(
    (key: TranslationKey | string, fallback?: string): string => {
      return (
        (dict[currentLang] as Record<string, string>)?.[key] ||
        (dict.en as Record<string, string>)?.[key] ||
        fallback ||
        key
      );
    },
    [currentLang]
  );

  return useMemo(() => ({ t, lang: currentLang }), [t, currentLang]);
}

/**
 * Helper to display localized role labels across views.
 */
export function getRoleLabel(role: string | undefined, t: (key: string) => string): string {
  if (!role) return t('roleMinor');
  const normalized = role.toLowerCase();
  switch (normalized) {
    case 'protagonist':
      return t('roleProtagonist');
    case 'antagonist':
      return t('roleAntagonist');
    case 'supporting':
      return t('roleSupporting');
    case 'minor':
      return t('roleMinor');
    default:
      return role;
  }
}
